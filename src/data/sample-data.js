function mergeWeights(base, overrides = {}) {
  return { ...base, ...overrides };
}

function makeCareer(blueprint, role) {
  return {
    slug: role.slug,
    name: role.name,
    category: blueprint.category,
    cluster: blueprint.cluster,
    shortDescription: role.shortDescription,
    dreamSignals: [...new Set([...(blueprint.dreamSignals || []), ...(role.dreamSignals || [])])],
    riasecWeights: mergeWeights(blueprint.riasecWeights, role.riasecWeights),
    personalityPreferences: mergeWeights(blueprint.personalityPreferences, role.personalityPreferences),
    trainingTimeCategory: role.trainingTimeCategory || blueprint.trainingTimeCategory,
    incomeMode: role.incomeMode || blueprint.incomeMode,
    remoteOption: role.remoteOption || blueprint.remoteOption,
    physicalDemand: role.physicalDemand || blueprint.physicalDemand,
    transitionCostScore: role.transitionCostScore ?? blueprint.transitionCostScore,
    demandScore: role.demandScore ?? blueprint.demandScore,
    ageFriendlyScore: role.ageFriendlyScore ?? blueprint.ageFriendlyScore,
    roadmapTrack: role.roadmapTrack || blueprint.roadmapTrack,
    keywords: role.keywords || [],
    keywordGate: role.keywordGate ?? false,
    proofOfWork: role.proofOfWork,
    publishAction: role.publishAction,
    interviewTarget: role.interviewTarget,
    firstRevenueOffer: role.firstRevenueOffer,
    realityNote: role.realityNote,
    proofLabel: role.proofLabel || "이번 주 결과물",
  };
}

